/**
 * 推定1RM（1回だけ挙げられる最大重量の推定値）の算出。
 *
 * 式は Epley `w × (1 + r/30)`。Brzycki は r=37 で発散するため上限のクランプが別途必要になり、
 * Lombardi は低レップでの精度が落ちる。Epley が最も普及していて説明もしやすい。
 */

/**
 * 算出対象にするレップ数の上限。これを超えるセットは**クランプではなく除外**する。
 *
 * Epley はレップ数に対して線形（1回あたり+3.3%）なので、上限を上げるほど推定値が素直に膨らむ。
 * それ以上に問題なのは、12回を超えたあたりから限界を決めるのが筋力そのものより筋持久力・
 * フォーム維持に移り、「1回だけ挙げられる重量」の外挿として成立しなくなること。
 *
 * クランプにしないのは、`50kg×25` を `50kg×12` として扱うと「それらしいが根拠の無い値」が
 * 点として残り、軽く流した日が偽の最高点になり得るため。除外なら空白になるだけで嘘をつかない。
 *
 * 12にしているのは、10だと8〜12回という筋肥大の標準レンジで「11・12回まで伸びた日」＝
 * 成長した日が丸ごと落ちてしまい、15だとデロード日・パンプ日（中重量×高レップ）が
 * 重い低レップを上回って偽の最高点を作るため。得失が入れ替わる点として12を取る。
 */
export const ONE_REP_MAX_REP_LIMIT = 12;

/**
 * 1セットぶんの推定1RM。算出できないセットは null（グラフの点としては単に存在しなくなる）。
 *
 * `reps = 1` を特例にしているのは、Epley を素通しすると `w × 1.033` になり、実測の1RMを
 * 記録した日が3.3%水増しされてしまうため。
 *
 * 重量が無い（自重で記録した加重種目・未入力）セットは対象外。`0` を弾くのは、加重種目で
 * 「加重なし」を 0 と打つ人と空欄にする人が同じ意図であり、扱いを揃える必要があるため。
 */
export function estimateOneRepMax(weight: number | null, reps: number | null): number | null {
  if (weight == null || weight <= 0) return null;
  if (reps == null || reps < 1 || reps > ONE_REP_MAX_REP_LIMIT) return null;
  if (reps === 1) return weight;
  // 同値タイの判定と chart-scale の EPS 比較を安定させるため、小数第1位で丸めて持つ
  return Math.round(weight * (1 + reps / 30) * 10) / 10;
}
