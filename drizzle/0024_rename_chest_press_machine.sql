-- プリセット種目「チェストプレス（マシン）」を「チェストプレスマシン」へ改名する。
--
-- マスタの括弧は「中身が別名のとき」に使う（チンニング（懸垂）／エリプティカル（クロストレーナー）／
-- ペックデック（バタフライマシン）／アダクターマシン（内転筋マシン）など）。この1件だけが
-- 「器具の限定」を括弧に入れた例外で、括弧の中身が名前として情報を足していなかった。
-- 他のマシン種目（ヒップスラストマシン・リアデルトマシン・グルートキックバックマシン等）と
-- 同じ接尾辞表記に揃える。
--
-- 0023 と同じく、WHERE で旧名を明示して自分で改名済みのユーザーの行には当てない。
-- こちらはリリース済みの名前なので、0023 と違って実際に既存ユーザーの行に当たる。
--
-- 0008_backfill_exercise_slug.sql が旧名を条件に slug を埋めているが、あちらは既に適用済みの
-- 過去のマイグレーションなので触らない（適用順も 0008 → 0024 で、後から旧名が復活することはない）。
UPDATE `exercises` SET `name` = 'チェストプレスマシン', `updated_at` = CAST(strftime('%s','now') AS INTEGER) * 1000
  WHERE `source` = 'preset' AND `slug` = 'chest_press_machine' AND `name` = 'チェストプレス（マシン）';
